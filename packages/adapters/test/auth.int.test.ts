import { createDb, type Db } from '@saas/database'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { createAuth, type AuthEmail } from '../src/auth/index.ts'

let db: Db
const sent: AuthEmail[] = []

const authWith = (requireEmailVerification: boolean) =>
  createAuth({
    db,
    baseURL: 'http://localhost:3000',
    secret: 'test-secret-test-secret-test-secret-0123',
    rateLimit: false,
    requireEmailVerification,
    sendVerificationEmail: async (email) => {
      sent.push(email)
    },
  })

const email = () => `user-${crypto.randomUUID()}@example.com`
const password = 'correct horse battery staple'

beforeAll(() => {
  db = createDb({ connectionString: process.env.DATABASE_URL! })
})
afterAll(async () => {
  await db.$disconnect()
})

describe('access layer (Better Auth on auth_*)', () => {
  it('sign-up creates only the access account, never a business user', async () => {
    const auth = authWith(false)
    const address = email()
    const { user } = await auth.api.signUpEmail({ body: { email: address, password, name: 'Ana' } })

    const access = await db.authUser.findUnique({ where: { id: user.id } })
    expect(access?.email).toBe(address)
    // UUID v7 generated by the app.
    expect(user.id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-/)
    expect(await db.user.findUnique({ where: { authUserId: user.id } })).toBeNull()

    const account = await db.authAccount.findFirst({ where: { userId: user.id } })
    expect(account?.providerId).toBe('credential')
    expect(account?.password).toBeTruthy()
    expect(account?.password).not.toContain(password)
  })

  it('signs in with the right password and rejects a wrong one', async () => {
    const auth = authWith(false)
    const address = email()
    await auth.api.signUpEmail({ body: { email: address, password, name: 'Ana' } })
    const ok = await auth.api.signInEmail({ body: { email: address, password } })
    expect(ok.token).toBeTruthy()
    expect(await db.authSession.count({ where: { token: ok.token } })).toBe(1)
    await expect(
      auth.api.signInEmail({ body: { email: address, password: 'wrong password 123' } }),
    ).rejects.toThrow()
  })

  it('rejects passwords shorter than 12 characters', async () => {
    await expect(
      authWith(false).api.signUpEmail({ body: { email: email(), password: 'short', name: 'x' } }),
    ).rejects.toThrow()
  })

  it('with verification required: sends the email and blocks sign-in until verified', async () => {
    const auth = authWith(true)
    const address = email()
    sent.length = 0
    await auth.api.signUpEmail({ body: { email: address, password, name: 'Ana' } })
    expect(sent).toHaveLength(1)
    expect(sent[0]?.to).toBe(address)
    expect(sent[0]?.url).toContain('/api/auth/verify-email')
    await expect(auth.api.signInEmail({ body: { email: address, password } })).rejects.toThrow()
  })
})
